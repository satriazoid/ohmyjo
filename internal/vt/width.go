package vt

// Rune width, following the Unicode East Asian Width property the way modern
// terminals do. vt10x had no width handling at all: every rune took exactly one
// cell, so a CJK glyph or an emoji shifted every following glyph on the row one
// column to the left and the grid drifted out of alignment with the column
// addresses the application believes it is writing to.
//
// The tables are sorted and searched with binary search rather than being
// expressed as a map, because a map of rune ranges would allocate at init and
// cost a hash lookup per rune on the hottest path in the emulator.

// span is an inclusive range of runes sharing a width.
type span struct {
	lo, hi rune
}

