func inSpans(spans []span, r rune) bool {
	lo, hi := 0, len(spans)-1
	for lo <= hi {
		mid := int(uint(lo+hi) >> 1)
		switch {
		case r < spans[mid].lo:
			hi = mid - 1
		case r > spans[mid].hi:
			lo = mid + 1
		default:
			return true
		}
	}
	return false
}

// RuneWidth reports how many terminal cells a rune occupies: 0 for combining
// marks and formatting characters, 2 for East Asian wide and fullwidth runes
// (including emoji), and 1 otherwise.
func RuneWidth(r rune) int {
	switch {
	case r < 0x300:
		// ASCII and Latin-1 are always single width; this is the hot path.
		return 1
	case r == 0:
		return 0
	case inSpans(zeroWidth, r):
		return 0
	case inSpans(doubleWidth, r):
		return 2
	default:
		return 1
	}
}

// StringWidth reports the number of cells a string occupies.
func StringWidth(s string) int {
	n := 0
	for _, r := range s {
		n += RuneWidth(r)
	}
	return n
}
